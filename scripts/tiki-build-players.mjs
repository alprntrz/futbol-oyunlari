#!/usr/bin/env node
/**
 * Tiki Taka Toe — build the player pool (step 2/2).
 *
 * Merges the scraped squads (scripts/.cache/raw-squads.json, produced by
 * tiki-scrape-squads.mjs) with the hand-curated set (scripts/tiki-curated.json,
 * which adds honor badges + aliases), then writes src/data/players.ts.
 *
 * Usage: node scripts/tiki-build-players.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const CURATED = JSON.parse(readFileSync("scripts/tiki-curated.json", "utf8"));
const { byId } = JSON.parse(readFileSync("scripts/.cache/raw-squads.json", "utf8"));

// club ids usable as criteria (must match src/lib/tiki.ts CLUBS)
const CRIT_CLUBS = new Set(["realmadrid","barcelona","atletico","sevilla","valencia","villarreal","bayern","dortmund","schalke","leverkusen","manutd","mancity","liverpool","chelsea","arsenal","tottenham","juventus","milan","inter","napoli","roma","psg","monaco","ajax","psv","porto","benfica","sporting","galatasaray","fenerbahce","besiktas"]);

// Transfermarkt nationality name → country id (criteria countries are canonical;
// others get a slug). Keep in sync with src/lib/tiki.ts COUNTRIES.
const NAT = { Brazil:"brazil", Argentina:"argentina", France:"france", Spain:"spain", Germany:"germany", Italy:"italy", Netherlands:"netherlands", England:"england", Portugal:"portugal", Belgium:"belgium", Croatia:"croatia", Uruguay:"uruguay", Turkey:"turkey", "Türkiye":"turkey" };
const SLUG_ALIAS = { cotedivoire: "ivorycoast", koreasouth: "southkorea", republicofireland: "ireland", northmacedonia: "macedonia", unitedstates: "usa", drcongo: "congo", bosniaherzegovina: "bosnia" };
const natId = (n) => { if (!n) return "unknown"; if (NAT[n]) return NAT[n]; const s = n.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g,"").replace(/[^a-z]/g,""); return SLUG_ALIAS[s] ?? s; };
const decode = (s) => s.replace(/&amp;/g,"&").replace(/&#0?39;/g,"'").replace(/&quot;/g,'"').trim();
const norm = (s) => s.toUpperCase().replaceAll("İ","I").replaceAll("Ş","S").replaceAll("Ğ","G").replaceAll("Ü","U").replaceAll("Ö","O").replaceAll("Ç","C").normalize("NFD").replace(/[̀-ͯ]/g,"").replace(/[^A-Z]/g,"");

const merged = new Map(); // normName -> {name, country, clubs:Set, badges?, aliases?}
for (const rec of Object.values(byId)) {
  const clubs = rec.clubs.filter((c) => CRIT_CLUBS.has(c));
  if (!clubs.length) continue;
  const name = decode(rec.name);
  const key = norm(name);
  if (!key) continue;
  const e = merged.get(key);
  if (e) clubs.forEach((c) => e.clubs.add(c));
  else merged.set(key, { name, country: natId(rec.nat), clubs: new Set(clubs) });
}
const scrapedCount = merged.size;

let curNew = 0;
for (const p of CURATED) {
  const key = norm(p.name);
  const e = merged.get(key);
  if (e) { p.clubs.forEach((c) => e.clubs.add(c)); e.country = p.country; if (p.badges) e.badges = p.badges; if (p.aliases) e.aliases = p.aliases; }
  else { merged.set(key, { name: p.name, country: p.country, clubs: new Set(p.clubs), badges: p.badges, aliases: p.aliases }); curNew++; }
}

// sort by "notability" so search surfaces well-known players first
const score = (p) => (p.badges ? p.badges.length * 100 : 0) + p.clubs.size;
const out = [...merged.values()]
  .filter((p) => p.clubs.size >= 1)
  .sort((a, b) => score(b) - score(a) || a.name.localeCompare(b.name))
  .map((p) => { const o = { name: p.name, country: p.country, clubs: [...p.clubs].sort() }; if (p.badges) o.badges = p.badges; if (p.aliases) o.aliases = p.aliases; return o; });

const header = `/**
 * Player database for Tiki Taka Toe — deep pool built from Transfermarkt club
 * squads merged with a hand-curated set that adds honor badges.
 * Generated by scripts/tiki-build-players.mjs — do not edit by hand; instead
 * edit scripts/tiki-curated.json (badges/aliases) or re-run the scraper.
 * Sorted by notability (badges, then club count) so search ranks stars first.
 */
export interface GridPlayer {
  name: string;
  /** Country id (see COUNTRIES in tiki.ts) */
  country: string;
  /** Club ids the player represented (see CLUBS in tiki.ts) */
  clubs: string[];
  /** Honor badges: "wc" World Cup, "ucl" Champions League, "ballon" Ballon d'Or, "euro" Euros */
  badges?: string[];
  /** Extra accepted answer strings beyond the full name */
  aliases?: string[];
  /** optional real face image path (user-supplied); falls back to an initials avatar */
  photo?: string;
}

`;
// Emit in chunks: a single 16k-element literal exceeds TypeScript's inference
// limit (TS2590), so split into typed sub-arrays and concat them.
const CHUNK = 4000;
const chunks = [];
for (let i = 0; i < out.length; i += CHUNK) chunks.push(out.slice(i, i + CHUNK));
const body = chunks.map((ch, i) => `const _P${i}: GridPlayer[] = [\n` + ch.map((p) => "  " + JSON.stringify(p) + ",").join("\n") + `\n];`).join("\n\n");
const exportLine = `\n\nexport const PLAYERS: GridPlayer[] = [${chunks.map((_, i) => `..._P${i}`).join(", ")}];\n`;
writeFileSync("src/data/players.ts", header + body + exportLine);
console.error(`scraped: ${scrapedCount}, curated-only added: ${curNew}, TOTAL: ${out.length} → src/data/players.ts`);
