#!/usr/bin/env node
/**
 * scripts/.cache/raw-values.json (taktik-scrape-values.mjs) → src/data/taktik-values.ts:
 * each player's peak Transfermarkt market value in € millions, by name. Pitch Chess
 * card costs come from it (src/lib/taktik/pool.ts). Generated — don't edit the output.
 */
import { readFileSync, writeFileSync } from "node:fs";

const raw = JSON.parse(readFileSync("scripts/.cache/raw-values.json", "utf8"));
const squads = JSON.parse(readFileSync("scripts/.cache/raw-squads.json", "utf8")).byId;
const out = {};
for (const [id, peak] of Object.entries(raw)) {
  const name = squads[id]?.name;
  if (name && peak > 0) out[name] = Math.round(peak / 100000) / 10;
}
const body = Object.entries(out)
  .sort((a, b) => b[1] - a[1])
  .map(([n, v]) => `  ${JSON.stringify(n)}: ${v},`)
  .join("\n");
writeFileSync(
  "src/data/taktik-values.ts",
  `/** Peak Transfermarkt market values (€m) by player name. Generated by scripts/taktik-build-values.mjs — do not edit. */\nexport const VALUES: Record<string, number> = {\n${body}\n};\n`
);
console.log(Object.keys(out).length, "values");
