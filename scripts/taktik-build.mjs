#!/usr/bin/env node
/**
 * Taktik Tahtası — per-player data the game needs on top of players.ts:
 *   - main club: the criteria club with the most seasons (scripts/.cache/raw-seasons.json)
 *   - position group G / D / M / F (scripts/.cache/raw-positions.json, most listed one)
 * Writes src/data/taktik.ts as two strings aligned with PLAYERS (one char per player)
 * so it stays small. "?" = unknown (the game falls back, see src/lib/taktik/pool.ts).
 *
 * Usage: node scripts/taktik-build.mjs   (re-run after either scrape)
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";

import { PLAYERS } from "../src/data/players.ts";

const CLUB_IDS = ["realmadrid","barcelona","atletico","sevilla","valencia","villarreal","bayern","dortmund","schalke","leverkusen","manutd","mancity","liverpool","chelsea","arsenal","tottenham","juventus","milan","inter","napoli","roma","psg","monaco","ajax","psv","porto","benfica","sporting","galatasaray","fenerbahce","besiktas"];
const CODE = "abcdefghijklmnopqrstuvwxyzABCDE"; // one char per club, same order as CLUB_IDS
const norm = (s) => s.toUpperCase().replaceAll("İ","I").replaceAll("Ş","S").replaceAll("Ğ","G").replaceAll("Ü","U").replaceAll("Ö","O").replaceAll("Ç","C").normalize("NFD").replace(/[̀-ͯ]/g,"").replace(/[^A-Z]/g,"");
const decode = (s) => s.replace(/&amp;/g,"&").replace(/&#0?39;/g,"'").replace(/&quot;/g,'"').trim();

// name → club season counts
const seasons = existsSync("scripts/.cache/raw-seasons.json") ? JSON.parse(readFileSync("scripts/.cache/raw-seasons.json", "utf8")) : { names: {}, squads: {} };
const clubSeasons = new Map(); // normName → { club: n }
for (const [key, ids] of Object.entries(seasons.squads)) {
  const club = key.slice(0, key.lastIndexOf("_"));
  for (const id of ids) {
    const n = norm(decode(seasons.names[id] ?? ""));
    if (!n) continue;
    const c = clubSeasons.get(n) ?? clubSeasons.set(n, {}).get(n);
    c[club] = (c[club] ?? 0) + 1;
  }
}

// name → position counts
const GROUP = (t) => (/Goalkeeper/i.test(t) ? "G" : /Back|Defen[cs]e|Sweeper|Libero/i.test(t) && !/Midfield/i.test(t) ? "D" : /Midfield/i.test(t) ? "M" : /Wing|Forward|Striker|Attack/i.test(t) ? "F" : null);
const posData = existsSync("scripts/.cache/raw-positions.json") ? JSON.parse(readFileSync("scripts/.cache/raw-positions.json", "utf8")) : { names: {}, pos: {} };
const posOf = new Map(); // normName → { G: n, ... }
for (const [id, counts] of Object.entries(posData.pos)) {
  const n = norm(decode(posData.names[id] ?? ""));
  if (!n) continue;
  const g = posOf.get(n) ?? posOf.set(n, {}).get(n);
  for (const [t, k] of Object.entries(counts)) {
    const grp = GROUP(t);
    if (grp) g[grp] = (g[grp] ?? 0) + k;
  }
}

let clubs = "";
let pos = "";
let clubHit = 0;
let posHit = 0;
for (const p of PLAYERS) {
  const n = norm(p.name);
  const counts = clubSeasons.get(n) ?? {};
  // only clubs the player is listed with in players.ts
  const best = p.clubs.filter((c) => CLUB_IDS.includes(c)).sort((a, b) => (counts[b] ?? 0) - (counts[a] ?? 0))[0];
  if (best && counts[best]) clubHit++;
  clubs += best ? CODE[CLUB_IDS.indexOf(best)] : "?";
  const pc = posOf.get(n);
  const g = pc ? Object.entries(pc).sort((a, b) => b[1] - a[1])[0]?.[0] : undefined;
  if (g) posHit++;
  pos += g ?? "?";
}

writeFileSync(
  "src/data/taktik.ts",
  `/**
 * Taktik Tahtası per-player data, one char per player in PLAYERS order.
 * Generated by scripts/taktik-build.mjs from Transfermarkt squads — do not edit.
 */
/** main club, a char from TAKTIK_CLUB_CODE ("?" = none) */
export const TAKTIK_CLUB = ${JSON.stringify(clubs)};
export const TAKTIK_CLUB_IDS = ${JSON.stringify(CLUB_IDS)};
export const TAKTIK_CLUB_CODE = ${JSON.stringify(CODE)};
/** position group: G goalkeeper, D defender, M midfielder, F forward, ? unknown */
export const TAKTIK_POS = ${JSON.stringify(pos)};
`
);
console.error(`${PLAYERS.length} players · main club from seasons ${clubHit} · positions ${posHit}`);
