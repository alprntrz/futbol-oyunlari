#!/usr/bin/env node
/**
 * Saudi and Egyptian clubs for Tic-Tac-Toe league grids → src/data/players-arab.ts.
 *
 * Reads the squads scraped by tiki-scrape-squads.mjs (the "arab-…" clubs, run with
 * ONLY=arab-hilal,… FROM=2000) and splits them in two, leaving src/data/players.ts
 * (and so every seeded daily game, Bingo, Mystery Player and Pitch Chess) as it is:
 *   ARAB_LINKS    players already in PLAYERS → the "arab-…" clubs they also played for
 *   ARAB_PLAYERS  players who only played for these clubs (among the criteria clubs)
 *
 * Usage: node scripts/arab-build-players.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

import { PLAYERS } from "../src/data/players.ts";

const { byId } = JSON.parse(readFileSync("scripts/.cache/raw-squads.json", "utf8"));

// same name folding and nationality ids as tiki-build-players.mjs
const NAT = { Brazil: "brazil", Argentina: "argentina", France: "france", Spain: "spain", Germany: "germany", Italy: "italy", Netherlands: "netherlands", England: "england", Portugal: "portugal", Belgium: "belgium", Croatia: "croatia", Uruguay: "uruguay", Turkey: "turkey", Türkiye: "turkey" };
const SLUG_ALIAS = { cotedivoire: "ivorycoast", koreasouth: "southkorea", republicofireland: "ireland", northmacedonia: "macedonia", unitedstates: "usa", drcongo: "congo", bosniaherzegovina: "bosnia" };
const natId = (n) => {
  if (!n) return "unknown";
  if (NAT[n]) return NAT[n];
  const s = n.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^a-z]/g, "");
  return SLUG_ALIAS[s] ?? s;
};
const decode = (s) => s.replace(/&amp;/g, "&").replace(/&#0?39;/g, "'").replace(/&quot;/g, '"').trim();
const norm = (s) => s.toUpperCase().replaceAll("İ", "I").replaceAll("Ş", "S").replaceAll("Ğ", "G").replaceAll("Ü", "U").replaceAll("Ö", "O").replaceAll("Ç", "C").normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^A-Z]/g, "");

const KNOWN = new Map(PLAYERS.map((p) => [norm(p.name), p.name]));

const links = new Map(); // PLAYERS name -> Set(arab clubs)
const extra = new Map(); // norm name -> { name, country, clubs:Set }
for (const rec of Object.values(byId)) {
  const clubs = rec.clubs.filter((c) => c.startsWith("arab-"));
  if (!clubs.length) continue;
  const name = decode(rec.name);
  const key = norm(name);
  if (!key) continue;
  const known = KNOWN.get(key);
  if (known) {
    const set = links.get(known) ?? new Set();
    clubs.forEach((c) => set.add(c));
    links.set(known, set);
    continue;
  }
  const e = extra.get(key);
  if (e) clubs.forEach((c) => e.clubs.add(c));
  else extra.set(key, { name, country: natId(rec.nat), clubs: new Set(clubs) });
}

const linkObj = Object.fromEntries([...links].sort((a, b) => a[0].localeCompare(b[0])).map(([n, s]) => [n, [...s].sort()]));
const players = [...extra.values()]
  .sort((a, b) => b.clubs.size - a.clubs.size || a.name.localeCompare(b.name))
  .map((p) => ({ name: p.name, country: p.country, clubs: [...p.clubs].sort() }));

const out = `/**
 * Saudi and Egyptian clubs for Tic-Tac-Toe league grids (Transfermarkt squads 2000–).
 * Generated by scripts/arab-build-players.mjs: do not edit by hand.
 * Kept apart from players.ts so seeded daily games and Pitch Chess don't change.
 */
import type { GridPlayer } from "./players";

/** Players already in PLAYERS → the "arab-…" clubs they also played for */
export const ARAB_LINKS: Record<string, string[]> = ${JSON.stringify(linkObj, null, 1).replace(/\n\s*/g, " ")};

/** Players who (among the criteria clubs) only played for these clubs */
export const ARAB_PLAYERS: GridPlayer[] = [
${players.map((p) => "  " + JSON.stringify(p) + ",").join("\n")}
];
`;
writeFileSync("src/data/players-arab.ts", out);
console.error(`links: ${links.size} known players, extra: ${players.length} → src/data/players-arab.ts`);
