#!/usr/bin/env node
/**
 * Kart Düellosu — per-player numbers for the stat questions (docs/design/kart-duellosu.md).
 * Reads scripts/.cache/raw-wikidata.json (duel-fetch-wikidata.mjs) and raw-seasons.json,
 * writes src/data/duel.ts: one compact row per card, keyed by the PLAYERS index.
 * A player becomes a card only with club appearances, height and date of birth.
 *
 * Usage: node scripts/duel-build.mjs
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

import { PLAYERS } from "../src/data/players.ts";

const norm = (s) => s.toUpperCase().replaceAll("İ", "I").replaceAll("Ş", "S").replaceAll("Ğ", "G").replaceAll("Ü", "U").replaceAll("Ö", "O").replaceAll("Ç", "C").normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^A-Z]/g, "");
const decode = (s) => s.replace(/&amp;/g, "&").replace(/&#0?39;/g, "'").replace(/&quot;/g, '"').trim();

const wd = JSON.parse(readFileSync("scripts/.cache/raw-wikidata.json", "utf8"));
const seasonsFile = JSON.parse(readFileSync("scripts/.cache/raw-seasons.json", "utf8"));

// Transfermarkt id → seasons in our big-club squads
const seasonsOf = new Map();
for (const ids of Object.values(seasonsFile.squads)) for (const id of ids) seasonsOf.set(id, (seasonsOf.get(id) ?? 0) + 1);

const byName = new Map();
for (const f of ["scripts/.cache/raw-seasons.json", "scripts/.cache/raw-positions.json"]) {
  if (!existsSync(f)) continue;
  for (const [id, name] of Object.entries(JSON.parse(readFileSync(f, "utf8")).names ?? {})) {
    const n = norm(decode(name));
    if (n) (byName.get(n) ?? byName.set(n, new Set()).get(n)).add(id);
  }
}

function numbers(e) {
  let apps = 0;
  let goals = 0;
  let clubs = 0;
  let caps = 0;
  let intGoals = 0;
  for (const s of Object.values(e.stints)) {
    if (s.nat) {
      // the senior team is the national stint with the most caps
      if (s.m > caps) [caps, intGoals] = [s.m, s.g];
    } else {
      apps += s.m;
      goals += s.g;
      clubs++;
    }
  }
  let height = e.height ?? 0;
  if (height > 0 && height < 3) height = Math.round(height * 100); // metres → cm
  const born = e.birth ? Number(e.birth.replaceAll("-", "")) : 0;
  return { apps, goals, clubs, caps, intGoals, height, born };
}

/** the duel's card pool: the best-known players only (the fetch covers everyone for ages) */
const DUEL_POOL = 4000;
const rows = [];
const seenQ = new Set();
// birth / death per player for the Tic-Tac-Toe search ("Midfielder · 34"), days since 1900-01-01
const DAY0 = Date.UTC(1900, 0, 1);
const days = (iso) => (iso ? Math.round((Date.parse(iso + "T00:00:00Z") - DAY0) / 86400000) : 0);
let born = "";
const died = {};
PLAYERS.forEach((p, i) => {
  const ids = [...(byName.get(norm(p.name)) ?? [])].filter((id) => wd[id]);
  // a name shared by two people: the one with more of our big-club seasons
  const id = ids.sort((a, b) => (seasonsOf.get(b) ?? 0) - (seasonsOf.get(a) ?? 0))[0];
  const e = id ? wd[id] : null;
  const b = e?.birth && e.birth > "1900" ? days(e.birth) : 0;
  born += b > 0 && b < 36 ** 3 ? b.toString(36).padStart(3, "0") : "000";
  if (b > 0 && e.death && e.death > e.birth) died[i] = days(e.death);
  if (!e || i >= DUEL_POOL) return;
  if (seenQ.has(e.q)) return;
  const n = numbers(e);
  if (n.apps < 20 || n.height < 150 || n.height > 210 || !n.born) return;
  seenQ.add(e.q);
  rows.push([i, n.apps, n.goals, n.caps, n.intGoals, n.height, n.born, n.clubs, seasonsOf.get(id) ?? 0, p.badges?.length ?? 0]);
});

const out = `/**
 * Kart Düellosu cards: career numbers per player (Wikidata, CC0; seasons from our
 * Transfermarkt squads; honours from players.ts). Generated by scripts/duel-build.mjs
 * — do not edit. Row: [PLAYERS index, club apps, club goals, caps, national goals,
 * height cm, born yyyymmdd (0 = unknown), clubs, big-club seasons, honours].
 */
export type DuelRow = [number, number, number, number, number, number, number, number, number, number];

export const DUEL_ROWS: DuelRow[] = ${JSON.stringify(rows)};
`;
writeFileSync("src/data/duel.ts", out);

writeFileSync(
  "src/data/born.ts",
  `/**
 * Birth (and death) dates per player, for "Midfielder · 34" in the player search.
 * Wikidata (CC0), matched through Transfermarkt ids. Generated by scripts/duel-build.mjs
 * — do not edit. BORN: 3 base-36 chars per PLAYERS index, days since 1900-01-01
 * ("000" = unknown). DIED: PLAYERS index → day of death, same count.
 */
export const BORN = ${JSON.stringify(born)};
export const DIED: Record<number, number> = ${JSON.stringify(died)};
`
);
console.error(`birth dates for ${born.match(/.{3}/g).filter((x) => x !== "000").length} of ${PLAYERS.length} players, ${Object.keys(died).length} died`);

// server.js can't import TypeScript: the numbers it needs to judge rounds and check the
// budget, by card id. Tiers follow the same rule as src/lib/duel.ts (fame order).
const server = {};
rows.forEach(([i, ...stats], rank) => (server[i] = [...stats, rank < 150 ? 3 : rank < 750 ? 2 : 1]));
mkdirSync("server-data", { recursive: true });
writeFileSync("server-data/duel-cards.json", JSON.stringify(server));
console.error(`${rows.length} cards → src/data/duel.ts (${Math.round(out.length / 1024)} KB)`);
