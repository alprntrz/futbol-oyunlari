#!/usr/bin/env node
/**
 * Tic-Tac-Toe honours with counts (step 2/2) → src/data/honours.ts.
 * Reads scripts/.cache/raw-honours.json (tiki-scrape-honours.mjs: title counts, top scorer
 * competitions), keyed back to PLAYERS names through the squad scrape's Transfermarkt ids.
 *
 * Usage: node --import ./scripts/lib/alias.mjs scripts/tiki-build-honours.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

import { PLAYERS } from "@/data/players";

const raw = JSON.parse(readFileSync("scripts/.cache/raw-honours.json", "utf8"));
const squads = JSON.parse(readFileSync("scripts/.cache/raw-squads.json", "utf8")).byId;

const norm = (s) => s.toUpperCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^A-Z]/g, "");
const known = new Map(PLAYERS.map((p) => [norm(p.name), p.name]));
const nameOfId = (id) => (squads[id] ? known.get(norm(squads[id].name.replace(/&#0?39;/g, "'").replace(/&amp;/g, "&"))) : undefined);

/** title headings on Transfermarkt → our ids (European Cup winners before 1992 have their own heading) */
const COUNT = {
  ucl2: { min: 2, titles: ["UEFA Champions League winner", "European Champion Clubs' Cup winner", "European Champions Cup winner"] },
  en3: { min: 3, titles: ["English champion"] },
  es3: { min: 3, titles: ["Spanish champion"] },
  it3: { min: 3, titles: ["Italian champion"] },
  de3: { min: 3, titles: ["German champion"] },
  fr3: { min: 3, titles: ["French champion"] },
  pt3: { min: 3, titles: ["Portuguese champion"] },
  tr3: { min: 3, titles: ["Turkish champion"] },
};
/** "Top goal scorer" competitions → our ids */
const TOP = {
  uclTop: ["UEFA Champions League", "European Champion Clubs' Cup", "European Champions Cup"],
  wcTop: ["World Cup"],
  euroTop: ["UEFA Euro", "European Championship"],
};

const out = Object.fromEntries([...Object.keys(COUNT), ...Object.keys(TOP)].map((k) => [k, new Set()]));
// (Transfermarkt's headings vary in case: "English Champion", "German Champion")
const low = (s) => s.toLowerCase();
for (const [id, h] of Object.entries(raw)) {
  const name = nameOfId(id);
  if (!name) continue;
  const titles = Object.fromEntries(Object.entries(h.titles).map(([t, n]) => [low(t), n]));
  for (const [k, { min, titles: names }] of Object.entries(COUNT)) {
    const n = names.reduce((a, t) => a + (titles[low(t)] ?? 0), 0);
    if (n >= min) out[k].add(name);
  }
  const top = h.top.map(low);
  for (const [k, comps] of Object.entries(TOP)) if (comps.some((c) => top.includes(low(c)))) out[k].add(name);
}

const ids = Object.keys(out);
const body = ids.map((k) => `  ${k}: ${JSON.stringify([...out[k]].sort())},`).join("\n");
writeFileSync(
  "src/data/honours.ts",
  `/**
 * Tic-Tac-Toe honours with counts (Transfermarkt achievements pages).
 * Generated by scripts/tiki-build-honours.mjs: do not edit by hand. Names as in players.ts.
 */
export type HonourId = ${ids.map((k) => JSON.stringify(k)).join(" | ")};

export const HONOURS: Record<HonourId, string[]> = {
${body}
};
`
);
console.error(ids.map((k) => `${k} ${out[k].size}`).join(", "));
