#!/usr/bin/env node
/**
 * Arabic player names from Wikidata (CC0), matched to our players through their Transfermarkt
 * id (property P2446), for the Arabic keyboard search in the app. Label plus alternative labels.
 * Output: scripts/.cache/raw-ar-names.json (resumable) → src/data/players-ar.ts.
 *
 * Usage: node scripts/ar-names-fetch.mjs   (CACHE_DIR = folder of raw-seasons / raw-positions)
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";

import { ARAB_PLAYERS } from "../src/data/players-arab.ts";
import { PLAYERS } from "../src/data/players.ts";

const CACHE_DIR = process.env.CACHE_DIR || "scripts/.cache";
const STATE = "scripts/.cache/raw-ar-names.json";
const OUT = "src/data/players-ar.ts";
const BATCH = 120;
const GAP_MS = 2500; // be gentle with the public endpoint
const RETRIES = 4;
const UA = "TiktakoDataBuild/1.0 (football quiz app; one-off batch)";
const ARABIC = /[؀-ۿ]/;

const norm = (s) => s.toUpperCase().replaceAll("İ", "I").normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^A-Z]/g, "");
const decode = (s) => s.replace(/&amp;/g, "&").replace(/&#0?39;/g, "'").replace(/&quot;/g, '"').trim();
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const readJson = (f) => (existsSync(f) ? JSON.parse(readFileSync(f, "utf8")) : {});

// our name → Transfermarkt ids seen under that name
const byName = new Map();
const addId = (id, name) => {
  const n = norm(decode(name));
  if (n) (byName.get(n) ?? byName.set(n, new Set()).get(n)).add(id);
};
for (const f of ["raw-seasons.json", "raw-positions.json"]) {
  for (const [id, name] of Object.entries(readJson(`${CACHE_DIR}/${f}`).names ?? {})) addId(id, name);
}
for (const [id, rec] of Object.entries(readJson("scripts/.cache/raw-squads.json").byId ?? {})) addId(id, rec.name);

const players = [...PLAYERS, ...ARAB_PLAYERS];
const state = readJson(STATE);
const want = [...new Set(players.flatMap((p) => [...(byName.get(norm(p.name)) ?? [])]))].filter((id) => !(id in state));
console.error(`${players.length} players, ${want.length} Transfermarkt ids to look up`);

async function query(ids) {
  const q = `SELECT ?tm ?l WHERE {
    VALUES ?tm { ${ids.map((i) => `"${i}"`).join(" ")} }
    ?p wdt:P2446 ?tm.
    { ?p rdfs:label ?l } UNION { ?p skos:altLabel ?l }
    FILTER(LANG(?l) = "ar")
  }`;
  for (let attempt = 1; ; attempt++) {
    const r = await fetch(`https://query.wikidata.org/sparql?format=json&query=${encodeURIComponent(q)}`, {
      headers: { "User-Agent": UA, Accept: "application/sparql-results+json" },
    });
    if (r.ok) return (await r.json()).results.bindings;
    if (attempt >= RETRIES) throw new Error(`Wikidata answered ${r.status}`);
    await sleep(GAP_MS * attempt * 2);
  }
}

for (let i = 0; i < want.length; i += BATCH) {
  const ids = want.slice(i, i + BATCH);
  const rows = await query(ids);
  for (const id of ids) state[id] = [];
  for (const row of rows) {
    const name = row.l.value.trim();
    if (ARABIC.test(name) && !state[row.tm.value].includes(name)) state[row.tm.value].push(name);
  }
  writeFileSync(STATE, JSON.stringify(state));
  console.error(`${Math.min(i + BATCH, want.length)} / ${want.length}`);
  await sleep(GAP_MS);
}

const entries = [];
for (const p of players) {
  const names = [...new Set([...(byName.get(norm(p.name)) ?? [])].flatMap((id) => state[id] ?? []))];
  if (names.length) entries.push([p.name, names.join("|")]);
}
writeFileSync(
  OUT,
  `/**
 * Arabic player names for the Arabic keyboard search (Latin name → names joined by "|").
 * Wikidata, CC0. Generated by scripts/ar-names-fetch.mjs: do not edit by hand.
 */
export const AR_PLAYERS: Record<string, string> = ${JSON.stringify(Object.fromEntries(entries))};
`,
);
console.error(`${entries.length} of ${players.length} players have an Arabic name → ${OUT}`);
